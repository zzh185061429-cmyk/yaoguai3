export const Schema = z.object({
  时间: z.object({
    当前日期时间: z.string().describe('格式为 MM月DD日 HH:mm，例如 10月08日 07:30').prefault('10月08日 07:30'),
    当前星期: z.enum(['周一', '周二', '周三', '周四', '周五', '周六', '周日']).prefault('周二'),
  }),

  状态: z.object({
    当前地点: z.string().prefault('沈家别墅'),
  }),

  今日派单: z.object({
    客户: z.enum(['温知晚', '周念安', '傅霁', '椎名律', '姜朝渔', '裴今歌', '罗兰', '霍千黎', '季明舒', '步玲燕', '陆时予', '许不倦', '待定']).prefault('待定'),
    描述: z.string().describe('客户下单的自然语言描述，符合角色人设').prefault('待生成'),
    预约时间: z.string().describe('格式 MM月DD日 HH:mm').prefault(''),
    服务时长: z.coerce.number().describe('服务小时数').prefault(0),
    价格: z.coerce.number().describe('该单预期收入').prefault(0),
  }),

  经济: z.object({
    总债务: z.coerce.number().prefault(300_000_000),
    累计收入: z.coerce.number().prefault(0),
    剩余债务: z.coerce.number().prefault(300_000_000),
  }).transform(data => ({
    ...data,
    剩余债务: Math.max(0, data.总债务 - data.累计收入),
  })),

  角色数据: z.record(
    z.enum(['温知晚', '周念安', '傅霁', '椎名律', '姜朝渔', '裴今歌', '罗兰', '霍千黎', '季明舒', '步玲燕', '陆时予', '许不倦']),
    z.object({
      剩余服务小时: z.coerce.number().describe('距离服务结束剩余的小时数，未开始时=服务时长，冻结不变').prefault(0),
      剩余服务分钟: z.coerce.number().describe('距离服务结束剩余的分钟数').prefault(0),
      服务状态: z.enum(['无服务', '未开始', '进行中']).describe('无服务→(派单)→未开始→(到预约时间)→进行中→(时间耗尽)→无服务').prefault('无服务'),
    })
  ).prefault({
    温知晚: { 剩余服务小时: 0, 剩余服务分钟: 0, 服务状态: '无服务' },
    周念安: { 剩余服务小时: 0, 剩余服务分钟: 0, 服务状态: '无服务' },
    傅霁: { 剩余服务小时: 0, 剩余服务分钟: 0, 服务状态: '无服务' },
    椎名律: { 剩余服务小时: 0, 剩余服务分钟: 0, 服务状态: '无服务' },
    姜朝渔: { 剩余服务小时: 0, 剩余服务分钟: 0, 服务状态: '无服务' },
    裴今歌: { 剩余服务小时: 0, 剩余服务分钟: 0, 服务状态: '无服务' },
    罗兰: { 剩余服务小时: 0, 剩余服务分钟: 0, 服务状态: '无服务' },
    霍千黎: { 剩余服务小时: 0, 剩余服务分钟: 0, 服务状态: '无服务' },
    季明舒: { 剩余服务小时: 0, 剩余服务分钟: 0, 服务状态: '无服务' },
    步玲燕: { 剩余服务小时: 0, 剩余服务分钟: 0, 服务状态: '无服务' },
    陆时予: { 剩余服务小时: 0, 剩余服务分钟: 0, 服务状态: '无服务' },
    许不倦: { 剩余服务小时: 0, 剩余服务分钟: 0, 服务状态: '无服务' },
  }),
});
export type Schema = z.output<typeof Schema>;
